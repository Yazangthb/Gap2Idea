"""Compute Stage A, Stage A+B, Stage A+B+C metrics on gold papers in one shot.

Reuses the SciBERT-FT output from data/scibert_prep/scibert_gold_gaps.tsv
(generated by test_scibert_gold.py). Applies the new context-aware GAP/JUNK
Stage C via OpenRouter (gpt-4o) on top, then reports a single consolidated
table of all 3 stages.

    python -u scripts/eval/eval_all_stages_gold.py --model openai/gpt-4o
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import time
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from gap2idea.pipeline.gap_funnel import slice_terminal_regions, token_containment  # noqa: E402
from gap2idea.pipeline.gap_prefilter import split_sentences  # noqa: E402
from gap2idea.pipeline.sections import _cut_before_references  # noqa: E402
from gap2idea.pipeline.llm import get_llm_client  # noqa: E402

# === GAP/JUNK prompt with context (same as test_gap_junk_context.py) ===
SYSTEM = (
    "For each numbered input, classify the highlighted sentence (between >>> <<<) "
    "as GAP or JUNK, using the surrounding context to disambiguate.\n\n"
    "GAP = the authors mention something NOT YET DONE in their own work:\n"
    "  - a limitation, weakness, or assumption of their method\n"
    "  - a scope restriction ('focuses only on English')\n"
    "  - a future-work direction ('we leave X for future work')\n"
    "  - an open problem or unanswered question\n\n"
    "JUNK = anything else: gratitude, numbered results, method/hyperparam descriptions, "
    "prior-work citations, truncated fragments.\n\n"
    "Output ONLY '<idx>. GAP' or '<idx>. JUNK' per line, nothing else."
)
SHOTS = [
    ("...evaluate on six benchmarks. >>> Our method achieves 95.2% accuracy, outperforming baselines by 3.1 points. <<< Detailed tables in Appendix A.", "JUNK"),
    ("...We acknowledge two main limitations. >>> First, our data augmentation strategy relies on cycle adversarial nets. <<< This dependence may limit applicability.", "GAP"),
    ("...thank our funding agency. >>> We would like to express our gratitude to Dr. Smith. <<< Their feedback helped shape the manuscript.", "JUNK"),
    ("...we use a single GPU. >>> We leave the multi-GPU implementation for future work. <<< This restricts our experiments to mid-sized models.", "GAP"),
    ("...Following preprocessing pipelines, >>> we use the commonly-used PaddleOCR to handle our dataset. <<< Recognition quality is reported in Section 3.", "JUNK"),
]


def find_context(sentence, full_text, window=30):
    short = sentence.strip()[:80]
    idx = full_text.find(short)
    if idx < 0:
        return "", ""
    end = idx + len(sentence)
    before = " ".join(full_text[max(0, idx-400):idx].split()[-window:])
    after = " ".join(full_text[end:end+400].split()[:window])
    return before, after


def judge_batch(client, model, items, batch=10):
    """items = list of (sentence, before, after). Returns list of bool (True = GAP/keep)."""
    shot_block = "\n".join(f"Example {k+1}: {s}\nLabel {k+1}: {a}" for k, (s, a) in enumerate(SHOTS))
    preds = [None] * len(items)
    for i in range(0, len(items), batch):
        chunk = items[i:i+batch]
        lines = []
        for k, (sent, before, after) in enumerate(chunk):
            ctx = f"{before} >>> {sent} <<< {after}".strip()
            lines.append(f"{k+1}. {ctx}")
        user = f"Reference examples:\n{shot_block}\n\nClassify:\n" + "\n".join(lines)
        try:
            resp = client.chat.completions.create(
                model=model,
                messages=[{"role": "system", "content": SYSTEM},
                          {"role": "user", "content": user}],
                temperature=0.0, max_tokens=10 * len(chunk))
            content = resp.choices[0].message.content
            ans = {}
            for ln in content.splitlines():
                m = re.match(r"\s*(\d+)\s*[.):\-]\s*(GAP|JUNK)", ln.strip(), re.IGNORECASE)
                if m:
                    ans[int(m.group(1))] = m.group(2).upper() == "GAP"
            for k in range(len(chunk)):
                preds[i+k] = ans.get(k+1, True)
        except Exception as e:
            print(f"  batch error: {e}", flush=True)
            for k in range(len(chunk)):
                preds[i+k] = True
    return preds


def gold_match(sent, gold_rows):
    for _, g in gold_rows.iterrows():
        if max(token_containment(g["gap_sentence"], sent),
               token_containment(sent, g["gap_sentence"])) >= 0.8:
            return g["gap_id"]
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="openai/gpt-4o")
    ap.add_argument("--gaps-tsv", default="data/scibert_prep/scibert_gold_gaps.tsv")
    args = ap.parse_args()

    # Load gold + gold paper texts
    gold = pd.read_csv(ROOT / "data/bench_gap/gold_sentences.tsv", sep="\t", dtype={"paper_id": str})
    papers = {}
    for line in (ROOT / "data/scibert_prep/gold_papers.jsonl").read_text(encoding="utf-8").splitlines():
        if line.strip():
            rec = json.loads(line)
            papers[str(rec["id"])] = rec
    print(f"Gold: {len(gold)} gaps over {gold['paper_id'].nunique()} papers", flush=True)
    print(f"Papers loaded: {len(papers)}", flush=True)

    # --- Stage A: localization recall (no model) ---
    print("\n=== Stage A (slice only) ===", flush=True)
    full_total = slice_total = 0
    loc_hits = {tau: 0 for tau in [0.90, 0.80, 0.70]}
    for pid, rec in papers.items():
        full_sents = split_sentences(_cut_before_references(rec["text"]))
        regions = slice_terminal_regions(rec["text"], blocks=rec.get("blocks"))
        slice_text = " ".join(s for r in regions for s in r.sentences)
        full_total += len(full_sents)
        slice_total += sum(len(r.sentences) for r in regions)
        for _, g in gold[gold["paper_id"] == pid].iterrows():
            c = token_containment(g["gap_sentence"], slice_text)
            for tau in loc_hits:
                if c >= tau:
                    loc_hits[tau] += 1
    drop = 1 - slice_total / max(1, full_total)
    print(f"  Full body: {full_total} sentences ({full_total/len(papers):.0f}/paper)")
    print(f"  → Slice:   {slice_total} sentences ({slice_total/len(papers):.0f}/paper)  drop={drop:.3f}")
    print(f"  Localization recall (gold gap in slice):")
    for tau, h in loc_hits.items():
        print(f"    τ={tau:.2f}: {h}/{len(gold)} = {h/len(gold):.3f}")

    # --- Stage A + B: SciBERT output ---
    print("\n=== Stage A + B (SciBERT-FT) ===", flush=True)
    df = pd.read_csv(ROOT / args.gaps_tsv, sep="\t", dtype=str).fillna("")
    print(f"  Stage B emitted: {len(df)} gaps ({len(df)/len(papers):.1f}/paper)")
    matched_b = set()
    for _, row in df.iterrows():
        m = gold_match(row["gap_sentence"], gold[gold["paper_id"] == row["paper_id"]])
        if m:
            matched_b.add(m)
    recall_b = len(matched_b) / len(gold)
    prec_b = sum(1 for _, r in df.iterrows() if gold_match(r["gap_sentence"], gold[gold["paper_id"] == r["paper_id"]])) / len(df)
    f1_b = 2 * recall_b * prec_b / max(1e-9, recall_b + prec_b)
    print(f"  Recall:           {len(matched_b)}/{len(gold)} = {recall_b:.3f}")
    print(f"  Precision (floor): {prec_b:.3f}  ← floor: gold is partial (silver), true precision higher")
    print(f"  F1 (floor):       {f1_b:.3f}")

    # --- Stage A + B + C: apply GAP/JUNK with context ---
    print(f"\n=== Stage A + B + C (+ GAP/JUNK LLM filter, {args.model}) ===", flush=True)
    items = []
    for _, row in df.iterrows():
        rec = papers.get(row["paper_id"])
        before, after = ("", "")
        if rec:
            before, after = find_context(row["gap_sentence"], rec["text"])
        items.append((row["gap_sentence"], before, after))

    client = get_llm_client()
    t0 = time.time()
    keep = judge_batch(client, args.model, items, batch=10)
    print(f"  LLM judgments: {len(items)} in {time.time()-t0:.1f}s", flush=True)

    df_c = df[keep].reset_index(drop=True)
    matched_c = set()
    for _, row in df_c.iterrows():
        m = gold_match(row["gap_sentence"], gold[gold["paper_id"] == row["paper_id"]])
        if m:
            matched_c.add(m)
    recall_c = len(matched_c) / len(gold)
    prec_c = (sum(1 for _, r in df_c.iterrows()
                  if gold_match(r["gap_sentence"], gold[gold["paper_id"] == r["paper_id"]]))
              / max(1, len(df_c)))
    f1_c = 2 * recall_c * prec_c / max(1e-9, recall_c + prec_c)
    print(f"  Stage C kept:     {len(df_c)}/{len(df)} ({len(df_c)/len(papers):.1f}/paper)")
    print(f"  Recall:           {len(matched_c)}/{len(gold)} = {recall_c:.3f}")
    print(f"  Precision (floor): {prec_c:.3f}")
    print(f"  F1 (floor):       {f1_c:.3f}")

    # Final table
    print("\n" + "=" * 70)
    print("CONSOLIDATED METRICS — Gap2Idea pipeline on 10 gold papers (19 gold gaps)")
    print("=" * 70)
    print(f"{'Stage':<32} {'recall':>8} {'P(floor)':>9} {'F1(floor)':>10} {'n_pred':>7}")
    print("-" * 70)
    print(f"{'Stage A (slice only, τ=0.80)':<32} {loc_hits[0.80]/len(gold):>8.3f} "
          f"{'-':>9} {'-':>10} {'-':>7}")
    print(f"{'Stage A + B (SciBERT-FT)':<32} {recall_b:>8.3f} {prec_b:>9.3f} "
          f"{f1_b:>10.3f} {len(df):>7}")
    print(f"{'Stage A + B + C ('+args.model.split('/')[-1]+')':<32} {recall_c:>8.3f} "
          f"{prec_c:>9.3f} {f1_c:>10.3f} {len(df_c):>7}")
    print()
    print(f"Cost: Stage A free, Stage B ~30ms/sentence, Stage C ~$0.001 per paper")


if __name__ == "__main__":
    main()
