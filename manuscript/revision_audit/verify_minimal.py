def prf(tp, fp, fn):
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    return dict(tp=tp, fp=fp, fn=fn, precision=p, recall=r,
                f1=2 * tp / (2 * tp + fp + fn) if 2 * tp + fp + fn else 0.0)


def score(rows, flags):
    tp = sum(bool(p) and r["label"] == 1 for r, p in zip(rows, flags))
    fp = sum(bool(p) and r["label"] == 0 for r, p in zip(rows, flags))
    fn = sum(not p and r["label"] == 1 for r, p in zip(rows, flags))
    return prf(tp, fp, fn)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    sources = ["stage_c_package/sal_criteria/sal_test_allmodels.json",
               "stage_c_package/sal_criteria/faithful_pubmed_verdicts.json",
               "stage_c_package/cost_tokens.csv", "stage_c_package/breadth_results.json",
               "stage_c_package/baseline_grid_results.json",
               "stage_c_package/cost_fullpaper_results.json",
               "stage_c_package/cost_perstage_results.json"]
    manifest = {p: hashlib.sha256((REPO / p).read_bytes()).hexdigest() for p in sources}
    rows = json.loads((REPO / sources[0]).read_text(encoding="utf-8"))
    verdicts = json.loads((REPO / sources[1]).read_text(encoding="utf-8"))
    assert len(rows) == 7968
    assert len({r["pmcid"] for r in rows}) == 40
    a = [r["sec"] in {"DISCUSS", "CONCL"} for r in rows]
    models = list(rows[0]["preds"])
    results = {m: {"full": score(rows, [bool(r["preds"][m]) for r in rows]),
                   "AB": score(rows, [bool(r["preds"][m]) and k for r, k in zip(rows, a)])}
               for m in models}
    pb = [bool(r["preds"]["PubMedBERT-FT"]) and k for r, k in zip(rows, a)]
    expected = {str(i) for i, p in enumerate(pb) if p}
    abc = {}
    for name in ["rct", "sal"]:
        assert set(verdicts[name]) == expected, "Incomplete or mismatched cached judge IDs"
        flags = [p and verdicts[name][str(i)] for i, p in enumerate(pb)]
        abc[name] = score(rows, flags)
    final = [p and verdicts["rct"][str(i)] for i, p in enumerate(pb)]
    bypaper = defaultdict(list)
    for i, r in enumerate(rows):
        bypaper[r["pmcid"]].append(i)
    counts = []
    for idx in bypaper.values():
        subset = [rows[i] for i in idx]
        counts.append((score(subset, [pb[i] for i in idx]), score(subset, [final[i] for i in idx])))
    rng = random.Random(20261013)
    distributions = [[], [], []]
    for _ in range(10000):
        sampled = [counts[rng.randrange(len(counts))] for _ in counts]
        f = []
        for j in [0, 1]:
            f.append(prf(*(sum(x[j][k] for x in sampled) for k in ["tp", "fp", "fn"]))["f1"])
        distributions[0].append(f[0]); distributions[1].append(f[1]); distributions[2].append(f[1] - f[0])
    intervals = {}
    for key, vals in zip(["AB", "ABC_rct", "paired_difference"], distributions):
        vals.sort()
        intervals[key] = [vals[249], vals[9749]]
    cost = list(csv.DictReader((REPO / sources[2]).open(encoding="utf-8")))
    sums = {k: sum(int(r[k]) for r in cost) for k in cost[0] if k != "paper"}
    assert sums["sents"] == len(rows) and sums["detpos_B"] == len(expected)
    result = dict(repo_commit=subprocess.check_output(["git", "-C", str(REPO), "rev-parse", "HEAD"], text=True).strip(),
                  source_sha256=manifest, SAL=dict(n=len(rows), papers=len(bypaper), gold=sum(r["label"] for r in rows),
                  A=score(rows, a), models=results, ABC=abc, conditional_cluster_bootstrap=intervals),
                  tokens=dict(totals=sums, ratio=sums["full_tokens"] / sums["funnel_tokens"]),
                  analysis_note="Offline metric recomputation. Bootstrap is descriptive and conditional on saved predictions; prompt selection used test feedback. No new inference or training.")
    (OUT / "verified_results.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    table = [r"% Auto-generated by revision_audit/verify_results.py", r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
             r"Stage-B detector & Full-stream $F_1$ & A+B precision & A+B recall & A+B $F_1$ \\", r"\midrule"]
    for m in models:
        x = results[m]
        table.append(f"{m.replace('(frozen)', ' (frozen)')} & {x['full']['f1']:.3f} & {x['AB']['precision']:.3f} & {x['AB']['recall']:.3f} & {x['AB']['f1']:.3f} " + r"\\")
    table.extend([r"\bottomrule", r"\end{tabular}"])
    (PAPER / "tables").mkdir(exist_ok=True)
    (PAPER / "tables/sal_detectors.tex").write_text("\n".join(table) + "\n", encoding="utf-8")
    table = [r"% Auto-generated from exact saved prediction/verdict IDs", r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
             r"Configuration & Kept & TP & Precision & Recall & $F_1$ \\", r"\midrule"]
    for name, x in [("Stage A", score(rows, a)), ("A+B: PubMedBERT", results['PubMedBERT-FT']['AB']),
                    ("A+B+C: RCT prompt", abc['rct']), ("A+B+C: SAL keep-biased", abc['sal'])]:
        table.append(f"{name} & {x['tp']+x['fp']} & {x['tp']} & {x['precision']:.3f} & {x['recall']:.3f} & {x['f1']:.3f} " + r"\\")
    table.extend([r"\bottomrule", r"\end{tabular}"])
    (PAPER / "tables/sal_stages.tex").write_text("\n".join(table) + "\n", encoding="utf-8")
    print(json.dumps({"SAL_ABC": abc, "descriptive_intervals": intervals, "tokens": sums, "ratio": result['tokens']['ratio']}, indent=2))






